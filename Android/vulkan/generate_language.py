"""Generate the Java catalog and localize the original APK's UI at build time."""
from pathlib import Path
import json
import re

ROOT=Path(__file__).resolve().parent

def catalog():
    rows=json.loads((ROOT/'assets/ui-language.json').read_text(encoding='utf-8'))
    english=[row[0] for row in rows]
    if len(set(english))!=len(english):raise ValueError('Duplicate English UI key')
    return rows

def generate():
    rows=catalog()
    lines=['package com.nakpaaiyaa.rbo;','// Generated by generate_language.py from assets/ui-language.json.',
           'final class AppLanguageCatalog {','    static final String[][] PAIRS = {']
    lines.extend('        {'+json.dumps(en,ensure_ascii=True)+','+json.dumps(th,ensure_ascii=True)+'},' for en,th in rows)
    lines+=['    };','}']
    (ROOT/'java/com/nakpaaiyaa/rbo/AppLanguageCatalog.java').write_text('\n'.join(lines)+'\n',encoding='utf-8')

def translate_smali():
    aliases={text for pair in catalog() for text in pair}
    literal=re.compile(r'^(\s*const-string(?:/jumbo)? ([vp]\d+), ("(?:[^"\\]|\\.)*"))$',re.M)
    for directory in (ROOT/'decoded').glob('smali*/com/nakpaaiyaa/rbo'):
        for path in directory.glob('*.smali'):
            code=path.read_text(encoding='utf-8')
            def inject(match):
                try:value=json.loads(match[3])
                except ValueError:return match[0]
                if value not in aliases:return match[0]
                reg=match[2]
                return match[0]+f'\n\n    invoke-static/range {{{reg} .. {reg}}}, Lcom/nakpaaiyaa/rbo/AppLanguage;->text(Ljava/lang/String;)Ljava/lang/String;\n    move-result-object {reg}'
            if path.name.startswith(('LauncherActivity','ControlsActivity','GameActivity','CheatMenu','TouchDirectionPad','GameControls')):
                code=literal.sub(inject,code)
            if path.name in ['LauncherActivity.smali','GameActivity.smali','ControlsActivity.smali']:
                anchor='    invoke-super {p0, p1}, Landroid/app/Activity;->onCreate(Landroid/os/Bundle;)V'
                if code.count(anchor)!=1:raise ValueError('Activity initialization anchor: '+str(path))
                code=code.replace(anchor,anchor+'\n\n    invoke-static/range {p0 .. p0}, Lcom/nakpaaiyaa/rbo/AppLanguage;->initialize(Landroid/app/Activity;)V',1)
                resume='    invoke-super {p0}, Landroid/app/Activity;->onResume()V'
                if resume in code:code=code.replace(resume,resume+'\n\n    invoke-static/range {p0 .. p0}, Lcom/nakpaaiyaa/rbo/AppLanguage;->initialize(Landroid/app/Activity;)V',1)
            # Final UI boundaries also handle strings assembled from cached
            # action names, state labels, exceptions, and formatted numbers.
            lines=[]
            for line in code.splitlines():
                match=re.search(r'invoke-(?:virtual|static)(?:/range)? \{([^}]+)\}, (.*)',line)
                reg=None
                if match:
                    target=match[2];args=match[1]
                    if ' .. ' in args:
                        first,last=args.split(' .. ')
                        regs=[first[0]+str(i) for i in range(int(first[1:]),int(last[1:])+1)] if first[0]==last[0] else []
                    else:regs=[r.strip() for r in args.split(',')]
                    ui=any(token in target for token in [
                        '->setText(Ljava/lang/CharSequence;)', '->setTitle(Ljava/lang/CharSequence;)',
                        '->setMessage(Ljava/lang/CharSequence;)', '->setContentDescription(Ljava/lang/CharSequence;)',
                        '->setPositiveButton(Ljava/lang/CharSequence;', '->setNegativeButton(Ljava/lang/CharSequence;',
                        '->setNeutralButton(Ljava/lang/CharSequence;',
                        'Landroid/widget/Toast;->makeText(Landroid/content/Context;Ljava/lang/CharSequence;'])
                    if ui and len(regs)>1:reg=regs[1]
                if match and path.name=='ControlsActivity.smali' and '->setSingleChoiceItems([Ljava/lang/CharSequence;' in match[2] and len(regs)>1:
                    array=regs[1]
                    lines += [f'    invoke-static/range {{{array} .. {array}}}, Lcom/nakpaaiyaa/rbo/AppLanguage;->strings([Ljava/lang/String;)[Ljava/lang/String;',f'    move-result-object {array}','']
                if reg:lines += [f'    invoke-static/range {{{reg} .. {reg}}}, Lcom/nakpaaiyaa/rbo/AppLanguage;->text(Ljava/lang/CharSequence;)Ljava/lang/String;',f'    move-result-object {reg}','']
                lines.append(line)
            path.write_text('\n'.join(lines)+'\n',encoding='utf-8')

if __name__=='__main__':generate()
